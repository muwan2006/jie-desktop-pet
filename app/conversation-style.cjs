function scene(text='',message={}){
 text=String(text).trim();
 if(message.fileRequested||message.backgroundTask)return 'explain';
 const detailed=/详细|展开(?:说|讲|解释|分析|一点|一下)|长文|教程|逐步|一步一步|完整(?:说明|解释|流程|步骤|介绍|分析)|(?:讲|说|解释|分析).{0,6}(?:原理|原因|过程)|(?:原理|分析|比较|解释)(?:一下|一下子|下|清楚)|怎么做|如何(?:实现|使用|安装|修复|解决|配置)/.test(text);
 if(detailed)return 'explain';
 const social=/哈哈|笑死|早[呀啊安上好]|晚安|你好|谢谢|摸摸|抱抱|吃瓜|离谱|又输了|又输啦|寄了|我服了|累死了|烦死了|绷不住|(?:怎么|为什么)(?:你|她|他|我).{0,8}(?:这么|那么|又|还).{0,5}(?:笨|傻|可爱|搞笑|离谱)|^(?:好[的呀啊吧]?|嗯[嗯哼]?|唉|哎|没事|算了)[。！!～~]*$/.test(text);
 const question=/是谁|是什么|哪里|哪个|搜索|查一下|核实|帮我|请问|怎么办|怎么修|怎么解决|为何|为什么.{0,12}(?:报错|失败|崩溃|连接|不能|无法)/.test(text);
 return social&&!question?'casual':'answer';
}
